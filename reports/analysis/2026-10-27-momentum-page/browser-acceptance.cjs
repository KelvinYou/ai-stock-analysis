const {chromium} = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, "../../..");
const out = __dirname;
fs.mkdirSync(out,{recursive:true});
(async () => {
  const browser = await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  const page = await browser.newPage({viewport:{width:1280,height:1000}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:3037/momentum',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Momentum Allocation',exact:true}).waitFor();
  assert(await page.getByText('Price only · No AI',{exact:true}).isVisible());
  const monthly = page.locator('section').filter({has:page.getByRole('heading',{name:'Monthly model basket',exact:true})});
  const monthlyLinks = await monthly.locator('a').evaluateAll(links=>links.map(a=>a.getAttribute('href')).sort());
  assert.deepEqual(monthlyLinks,['/NVDA','/TSM','/UNH']);
  const rows=page.getByRole('region',{name:'Daily momentum ranking'}).getByRole('row');
  assert.equal(await rows.count(),9);
  for (const [i,ticker] of ['TSM','V','UNH'].entries()) assert((await rows.nth(i+1).innerText()).includes(ticker));
  await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('aside').getBoundingClientRect().right<=1);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true,animations:'disabled'});
  await page.goto('http://127.0.0.1:3037/allocation',{waitUntil:'networkidle'});
  await page.getByRole('tab',{name:'Current snapshot',exact:true}).click();
  await page.getByRole('heading',{name:'Current momentum ranking',exact:true}).waitFor();
  const data=JSON.parse(fs.readFileSync(path.join(root,'web/data/momentum.json'),'utf8'));
  await page.clock.install({time:new Date(Date.parse(data.generated_at_utc)+7*86400000)});
  await page.goto('http://127.0.0.1:3037/momentum',{waitUntil:'networkidle'});
  assert.equal(await page.getByRole('region',{name:'Daily momentum ranking'}).count(),0);
  assert.equal(await page.locator('section').filter({has:page.getByRole('heading',{name:'Monthly model basket',exact:true})}).locator('a').count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS standalone page with unavailable analysis backend, monthly/daily baskets, desktop/mobile, expiry and Allocation regression.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
